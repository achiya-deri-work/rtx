"""Print the source-derived public API reference, or --check its freshness.

AST-only: does not import Torch, CuTe, or initialize CUDA. Inherited fields are
documented by their base class; this reference reports local declarations.
"""
import argparse
import ast
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def source(module):
    path=ROOT.joinpath(*module.split(".")).with_suffix(".py")
    if not path.exists():
        path=ROOT.joinpath(*module.split("."),"__init__.py")
    return path,ast.parse(path.read_text())


def declaration(module,name,seen=None):
    seen=set() if seen is None else seen
    if (module,name) in seen:
        return None
    seen.add((module,name))
    path,tree=source(module)
    for node in tree.body:
        if isinstance(node,(ast.ClassDef,ast.FunctionDef)) and node.name==name:
            return path,node
        if isinstance(node,ast.ImportFrom):
            for alias in node.names:
                if (alias.asname or alias.name)!=name:
                    continue
                if node.level:
                    package=module.split(".") if path.name=="__init__.py" else module.split(".")[:-1]
                    parent=package[:len(package)-node.level+1]
                    target=".".join(parent+([node.module] if node.module else []))
                else:
                    target=node.module or ""
                if target.startswith("rtx"):
                    return declaration(target,alias.name,seen)
    return None


def render():
    _,tree=source("rtx")
    exports=next(ast.literal_eval(n.value) for n in tree.body
                 if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=="_LAZY_EXPORTS" for t in n.targets))
    stable=next(ast.literal_eval(n.value) for n in tree.body
                if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=="_STABLE_EXPORTS" for t in n.targets))
    lines=["# Generated public API reference","",
           "Generated by `python tools/doc_reference.py`; checked against source without importing CUDA.",
           "See [API map](api.md) and [manual](README.md) for contracts and examples.",
           "Signatures/default expressions are source-level, not a claim that every combination is legal.",
           "Configuration listings show locally declared fields; inherited fields follow the named bases.",
           "`rtx.__version__` is the package version. Stable below means wildcard-export membership,",
           "not a declaration that this development checkout is a released 1.0 build.",""]
    for name,(module,attribute) in exports.items():
        provider="rtx."+module
        found=declaration(provider,attribute)
        lines += ["## `rtx."+name+"`","",("Stable runtime export" if name in stable else "Explicit feature/compatibility export")+
                  f"; provider `{provider}.{attribute}`.",""]
        if found is None:
            path,_=source(provider)
            lines += [f"Alias, constant, or re-export; see [source](../{path.relative_to(ROOT).as_posix()}).",""]
            continue
        path,node=found
        lines += [f"[Source](../{path.relative_to(ROOT).as_posix()})",""]
        doc=ast.get_docstring(node)
        if doc:
            lines += [doc.split("\n\n")[0].replace("\n"," "),""]
        snippets=[]
        if isinstance(node,ast.FunctionDef):
            snippets.append(f"{name}({ast.unparse(node.args)})")
        else:
            bases=", ".join(ast.unparse(b) for b in node.bases)
            snippets.append(f"class {name}"+(f"({bases})" if bases else "")+":")
            for item in node.body:
                if isinstance(item,ast.AnnAssign) and isinstance(item.target,ast.Name) and not item.target.id.startswith("_"):
                    snippets.append("    "+ast.unparse(item))
                if isinstance(item,ast.FunctionDef) and (not item.name.startswith("_") or item.name=="__init__"):
                    snippets.append(f"    def {item.name}({ast.unparse(item.args)})")
        lines += ["```python",*snippets,"```",""]
    return "\n".join(lines).rstrip()+"\n"


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    mode=parser.add_mutually_exclusive_group()
    mode.add_argument("--check",action="store_true")
    mode.add_argument("--write",action="store_true",help="Regenerate docs/api_reference.md")
    args=parser.parse_args()
    expected=render()
    if args.check:
        if (ROOT/"docs/api_reference.md").read_text()!=expected:
            raise SystemExit("API reference is stale; regenerate with tools/doc_reference.py")
        print("API reference matches source")
    elif args.write:
        (ROOT/"docs/api_reference.md").write_text(expected)
    else:
        print(expected,end="")


if __name__=="__main__":
    main()
